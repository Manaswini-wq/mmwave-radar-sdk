#!/usr/bin/env python3
"""
sensor_config_tool.py - CLI tool for mmWave radar sensor configuration.

Reads a YAML/JSON configuration file, validates parameters against platform
limits, calculates derived radar parameters, and generates a C header with
the corresponding config structs.

Usage:
    python sensor_config_tool.py --input config.yaml --output mmwave_user_cfg.h
    python sensor_config_tool.py --input config.json --platform awr2944 --calc
"""

import argparse
import json
import os
import sys
from pathlib import Path

try:
    import yaml
except ImportError:
    yaml = None

# Speed of light (m/s)
C = 3.0e8

# Platform limits: (max_bw_ghz, max_adc_rate_ksps, max_tx_power_dbm)
PLATFORM_LIMITS = {
    "awr2944": (5.0, 22500, 12.0),
    "iwr6843": (4.0, 12500, 12.0),
    "awr1843": (4.0, 12500, 12.0),
}


def load_config(path: str) -> dict:
    """Load a YAML or JSON configuration file."""
    ext = Path(path).suffix.lower()
    with open(path, "r") as f:
        if ext in (".yaml", ".yml"):
            if yaml is None:
                sys.exit("ERROR: pyyaml is required for YAML files.  pip install pyyaml")
            return yaml.safe_load(f)
        return json.load(f)


def validate_config(cfg: dict, platform: str) -> list:
    """Validate configuration against platform limits.  Returns list of errors."""
    errors = []
    max_bw, max_adc, max_tx = PLATFORM_LIMITS.get(platform, (4.0, 12500, 12.0))

    chirp = cfg.get("chirp_profile", {})
    start_freq = chirp.get("start_freq_ghz", 77.0)
    slope = chirp.get("freq_slope_mhz_us", 70.0)
    ramp_time = chirp.get("ramp_end_time_us", 40.0)
    adc_rate = chirp.get("sample_rate_ksps", 10000)

    bandwidth_ghz = slope * ramp_time / 1000.0
    if bandwidth_ghz > max_bw:
        errors.append(f"Bandwidth {bandwidth_ghz:.2f} GHz exceeds platform max {max_bw} GHz")

    if not (76.0 <= start_freq <= 81.0):
        errors.append(f"Start frequency {start_freq} GHz outside 76-81 GHz band")

    if adc_rate > max_adc:
        errors.append(f"ADC rate {adc_rate} ksps exceeds platform max {max_adc} ksps")

    frame = cfg.get("frame_config", {})
    chirps = frame.get("chirps_per_frame", 128)
    if chirps < 1 or chirps > 256:
        errors.append(f"chirps_per_frame={chirps} out of range [1, 256]")

    return errors


def calc_derived(cfg: dict) -> dict:
    """Calculate derived radar parameters."""
    chirp = cfg.get("chirp_profile", {})
    slope = chirp.get("freq_slope_mhz_us", 70.0)
    ramp_time = chirp.get("ramp_end_time_us", 40.0)
    adc_samples = chirp.get("adc_samples", 256)
    adc_rate_ksps = chirp.get("sample_rate_ksps", 10000)
    idle_time = chirp.get("idle_time_us", 7.0)
    start_freq = chirp.get("start_freq_ghz", 77.0)

    frame = cfg.get("frame_config", {})
    chirps = frame.get("chirps_per_frame", 128)
    tx_mask = frame.get("tx_channel_mask", 0x07)
    num_tx = bin(tx_mask).count("1")

    bw_ghz = slope * ramp_time / 1000.0
    bw_hz = bw_ghz * 1e9
    if_bw_mhz = slope * adc_samples / (adc_rate_ksps * 1.0)
    range_res_m = C / (2.0 * bw_hz)
    max_range_m = (adc_rate_ksps * 1e3 * C) / (2.0 * slope * 1e12)
    chirp_time_us = idle_time + ramp_time
    wavelength_m = C / (start_freq * 1e9)
    vel_res_mps = wavelength_m / (2.0 * chirps * chirp_time_us * 1e-6 * num_tx)

    return {
        "bandwidth_ghz": round(bw_ghz, 3),
        "if_bandwidth_mhz": round(if_bw_mhz, 3),
        "range_resolution_m": round(range_res_m, 4),
        "max_range_m": round(max_range_m, 2),
        "velocity_resolution_mps": round(vel_res_mps, 4),
        "chirp_cycle_time_us": round(chirp_time_us, 2),
    }


def generate_header(cfg: dict, derived: dict, output: str):
    """Generate a C header file with configuration structs."""
    chirp = cfg.get("chirp_profile", {})
    frame = cfg.get("frame_config", {})

    lines = [
        "/* Auto-generated by sensor_config_tool.py -- DO NOT EDIT */",
        "#ifndef MMWAVE_USER_CFG_H",
        "#define MMWAVE_USER_CFG_H",
        "",
        '#include "mmwave_types.h"',
        "",
        "/* Derived parameters */",
    ]
    for key, val in derived.items():
        macro = f"MMWAVE_DERIVED_{key.upper()}"
        lines.append(f"#define {macro}  ({val}f)")

    lines += [
        "",
        "static const mmwave_config_t g_user_config = {",
        "    .chirp_profile = {",
        f"        .profile_id        = {chirp.get('profile_id', 0)},",
        f"        .start_freq_ghz    = {chirp.get('start_freq_ghz', 77.0)}f,",
        f"        .freq_slope_mhz_us = {chirp.get('freq_slope_mhz_us', 70.0)}f,",
        f"        .idle_time_us      = {chirp.get('idle_time_us', 7.0)}f,",
        f"        .adc_start_time_us = {chirp.get('adc_start_time_us', 6.0)}f,",
        f"        .ramp_end_time_us  = {chirp.get('ramp_end_time_us', 40.0)}f,",
        f"        .adc_samples       = {chirp.get('adc_samples', 256)},",
        f"        .sample_rate_ksps  = {chirp.get('sample_rate_ksps', 10000)},",
        f"        .rx_gain_db        = {chirp.get('rx_gain_db', 30)},",
        f"        .tx_power_backoff_db = {chirp.get('tx_power_backoff_db', 0)}",
        "    },",
        "    .frame_config = {",
        f"        .chirps_per_frame     = {frame.get('chirps_per_frame', 128)},",
        f"        .num_frames           = {frame.get('num_frames', 0)},",
        f"        .frame_periodicity_ms = {frame.get('frame_periodicity_ms', 33.33)}f,",
        f"        .tx_channel_mask      = 0x{frame.get('tx_channel_mask', 7):02X},",
        f"        .rx_channel_mask      = 0x{frame.get('rx_channel_mask', 15):02X},",
        f"        .profile_id           = {frame.get('profile_id', 0)}",
        "    },",
        "    .data_output_mode = 0",
        "};",
        "",
        "#endif /* MMWAVE_USER_CFG_H */",
    ]

    with open(output, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"Generated {output}")


def main():
    parser = argparse.ArgumentParser(description="mmWave Sensor Configuration Tool")
    parser.add_argument("--input", "-i", required=True, help="YAML or JSON config file")
    parser.add_argument("--output", "-o", default="mmwave_user_cfg.h",
                        help="Output C header path")
    parser.add_argument("--platform", "-p", default="iwr6843",
                        choices=PLATFORM_LIMITS.keys(), help="Target platform")
    parser.add_argument("--calc", action="store_true",
                        help="Print derived parameters and exit")
    args = parser.parse_args()

    cfg = load_config(args.input)

    errors = validate_config(cfg, args.platform)
    if errors:
        for e in errors:
            print(f"VALIDATION ERROR: {e}", file=sys.stderr)
        sys.exit(1)

    derived = calc_derived(cfg)

    if args.calc:
        print("Derived radar parameters:")
        for k, v in derived.items():
            print(f"  {k}: {v}")
        return

    generate_header(cfg, derived, args.output)


if __name__ == "__main__":
    main()
