#!/usr/bin/perl
# api_doc_generator.pl - Auto-generate Markdown API documentation from
# Doxygen-style comments in C header files.
#
# Parses @file, @brief, @param, @return tags and produces a single
# Markdown document with a table of contents and cross-referenced
# function signatures.
#
# Usage:
#   perl api_doc_generator.pl --src sdk/app_api --out docs/api_reference.md

use strict;
use warnings;
use Getopt::Long;
use File::Find;

my $src_dir = 'sdk/app_api';
my $out_file = 'docs/api_reference.md';
GetOptions(
    'src=s' => \$src_dir,
    'out=s' => \$out_file,
) or die "Usage: $0 --src <dir> --out <file>\n";

# Collect all .h files
my @headers;
File::Find::find(sub {
    push @headers, $File::Find::name if /\.h$/;
}, $src_dir);

@headers = sort @headers;

# Parse each header
my @modules;   # [ { file, brief, functions => [ {name, brief, params, ret, sig} ] } ]

for my $hfile (@headers) {
    open my $fh, '<', $hfile or die "Cannot open $hfile: $!\n";
    my @lines = <$fh>;
    close $fh;

    my %module = (file => $hfile, brief => '', functions => []);

    my ($in_comment, $cur) = (0, undef);
    for (my $i = 0; $i <= $#lines; $i++) {
        my $line = $lines[$i];

        if ($line =~ m{/\*\*}) {
            $in_comment = 1;
            $cur = { brief => '', params => [], ret => '', sig => '' };
            next;
        }
        if ($in_comment && $line =~ m{\*/}) {
            $in_comment = 0;
            # Next non-blank line is the function signature
            for (my $j = $i + 1; $j <= $#lines; $j++) {
                next if $lines[$j] =~ /^\s*$/;
                chomp(my $sig = $lines[$j]);
                $sig =~ s/^\s+//;
                # Grab continuation lines until we see a semicolon
                while ($sig !~ /;/) {
                    $j++;
                    last if $j > $#lines;
                    chomp(my $cont = $lines[$j]);
                    $cont =~ s/^\s+/ /;
                    $sig .= $cont;
                }
                $cur->{sig} = $sig;
                ($cur->{name}) = $sig =~ /(\w+)\s*\(/;
                last;
            }
            push @{$module{functions}}, $cur if $cur->{name};
            $cur = undef;
            next;
        }
        if ($in_comment && $cur) {
            if ($line =~ /\@file\s+(.+)/) {
                $module{file_tag} = $1;
            } elsif ($line =~ /\@brief\s+(.+)/) {
                if (!$cur->{name}) {
                    # Could be module-level brief
                    $module{brief} ||= $1;
                }
                $cur->{brief} = $1;
            } elsif ($line =~ /\@param(?:\[(\w+)\])?\s+(\w+)\s+(.+)/) {
                push @{$cur->{params}}, { dir => $1 || '', name => $2, desc => $3 };
            } elsif ($line =~ /\@return\s+(.+)/) {
                $cur->{ret} = $1;
            }
        }
    }
    push @modules, \%module if @{$module{functions}};
}

# Generate Markdown
open my $out, '>', $out_file or die "Cannot write $out_file: $!\n";

print $out "# mmWave Radar SDK - API Reference\n\n";
print $out "*Auto-generated by `api_doc_generator.pl`*\n\n";

# Table of contents
print $out "## Table of Contents\n\n";
for my $mod (@modules) {
    my $anchor = lc($mod->{file});
    $anchor =~ s/[^a-z0-9]+/-/g;
    print $out "- [$mod->{file}](#$anchor)\n";
    for my $fn (@{$mod->{functions}}) {
        my $fa = lc($fn->{name});
        print $out "  - [`$fn->{name}`](#$fa)\n";
    }
}
print $out "\n---\n\n";

# Detailed sections
for my $mod (@modules) {
    print $out "## $mod->{file}\n\n";
    print $out "$mod->{brief}\n\n" if $mod->{brief};

    for my $fn (@{$mod->{functions}}) {
        print $out "### `$fn->{name}`\n\n";
        print $out "$fn->{brief}\n\n" if $fn->{brief};
        print $out "```c\n$fn->{sig}\n```\n\n";

        if (@{$fn->{params}}) {
            print $out "| Direction | Parameter | Description |\n";
            print $out "|-----------|-----------|-------------|\n";
            for my $p (@{$fn->{params}}) {
                my $dir = $p->{dir} ? "[$p->{dir}]" : "";
                print $out "| $dir | `$p->{name}` | $p->{desc} |\n";
            }
            print $out "\n";
        }
        print $out "**Returns:** $fn->{ret}\n\n" if $fn->{ret};
        print $out "---\n\n";
    }
}

close $out;
print "Generated $out_file with " . scalar(@modules) . " module(s).\n";
